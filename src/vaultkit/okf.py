"""The parts of the Open Knowledge Format that aren't a single note: the
reserved index.md and log.md files, and the conformance check.

Spec: https://github.com/GoogleCloudPlatform/knowledge-catalog/blob/main/okf/SPEC.md
"""

import os
import re
from pathlib import Path
from urllib.parse import quote

from . import vault as V

GENERATED = "<!-- Generated by vaultkit from frontmatter; edits here are overwritten. -->"
DATE_HEADING = re.compile(r"^## (\d{4}-\d{2}-\d{2})\s*$")
LIFECYCLE = {"draft", "stable", "deprecated"}


def link(v, from_dir, note):
    """A relative markdown link. Relative rather than bundle-absolute, because
    Obsidian reads a leading `/` as the vault root, not the bundle's."""
    rel = os.path.relpath(note.path, from_dir)
    return f"[{note.title}]({quote(Path(rel).as_posix())})"


def entry(v, from_dir, note):
    desc = note.description
    return f"- {link(v, from_dir, note)}" + (f" — {desc}" if desc else "")


# ---------------------------------------------------------------- log.md

def log(v, verb, text):
    """Append a dated bullet to the bundle's log.md, newest date first (§9)."""
    path = v.bundle / "log.md"
    day = V.today()
    body = path.read_text(encoding="utf-8") if path.exists() else f"# {v.name} log\n"
    bullet = f"- **{verb}** {text}"
    if m := re.search(rf"(?m)^## {day}[ \t]*\n", body):
        nxt = re.search(r"(?m)^## ", body[m.end():])
        end = m.end() + nxt.start() if nxt else len(body)
        today = body[m.end():end].rstrip("\n")
        body = body[:m.end()] + today + "\n" + bullet + "\n\n" + body[end:]
    elif first := re.search(r"(?m)^## ", body):
        body = body[:first.start()] + f"## {day}\n\n{bullet}\n\n" + body[first.start():]
    else:
        body = body.rstrip("\n") + f"\n\n## {day}\n\n{bullet}\n"
    path.write_text(re.sub(r"\n{3,}", "\n\n", body).rstrip("\n") + "\n", encoding="utf-8")


# ---------------------------------------------------------------- index.md

def folder_index(v, folder, title, notes, index_by):
    lines = [GENERATED, f"# {title}", ""]
    if index_by:
        grouped = V.groups(notes, index_by)
        loose = [n for n in notes if not V.listed(n.fields, index_by)]
        sections = list(grouped.items()) + ([("Other", loose)] if loose else [])
    else:
        sections = [("Notes", notes)]
    for heading, ns in sections:
        lines += [f"## {heading}", ""] + [entry(v, folder, n) for n in ns] + [""]
    if not notes:
        lines += ["## Notes", "", "Nothing here yet.", ""]
    return "\n".join(lines).rstrip("\n") + "\n"


def write_indexes(v):
    """One index.md per folder plus the bundle root's, all from frontmatter,
    so `description:` is what a reader or an agent sees first (§8)."""
    sections = []
    roots = []
    for t in v.templates.values():
        if not t.folder:
            roots = V.notes_in(v, t.name)
            continue
        d = v.bundle / t.folder
        if not d.is_dir():
            continue
        notes = V.notes_in(v, t.name)
        title = t.folder.replace("-", " ").capitalize()
        (d / "index.md").write_text(folder_index(v, d, title, notes, t.index_by),
                                    encoding="utf-8")
        sections.append((title, d, t.description, len(notes)))
    if v.sources.is_dir():
        notes = [V.Note(f, v.concept_id(f), *V.read(f))
                 for f in sorted(v.sources.glob("*.md")) if f.name not in V.RESERVED]
        (v.sources / "index.md").write_text(
            folder_index(v, v.sources, "Sources", notes, ""), encoding="utf-8")
        sections.append(("Sources", v.sources, "Archived full text of what was read.",
                         len(notes)))

    lines = ["---", f'okf_version: "{v.okf_version}"', "---", GENERATED, f"# {v.name}", ""]
    if roots:
        lines += ["## Notes", ""] + [entry(v, v.bundle, n) for n in roots] + [""]
    lines += ["## Sections", ""]
    for title, d, desc, n in sections:
        rel = quote(os.path.relpath(d / "index.md", v.bundle))
        lines.append(f"- [{title}]({rel}) — {desc or title} ({n})")
    lines.append("")
    (v.bundle / "index.md").write_text("\n".join(lines), encoding="utf-8")


# ---------------------------------------------------------------- check

def _aware(value):
    return V.when(value) is not None


def check_concept(v, path, problems):
    err = lambda m: problems.append(("error", path, m))  # noqa: E731
    warn = lambda m: problems.append(("warning", path, m))  # noqa: E731
    text = path.read_text(encoding="utf-8")
    try:
        fields, _ = V.parse(text)
    except Exception as e:
        err(f"frontmatter is not parseable YAML: {str(e).splitlines()[0]}")
        return
    if fields is None:
        err("no frontmatter block")
        return
    if not isinstance(fields, dict):
        err("frontmatter is not a mapping")
        return
    t = fields.get("type")
    if not isinstance(t, str) or not t.strip():
        err("`type` is missing or empty")
    if not fields.get("description"):
        warn("no `description` (recommended; index.md falls back to the body)")
    if "status" in fields and fields["status"] not in LIFECYCLE:
        warn(f"`status: {fields['status']}` is not draft/stable/deprecated in OKF")
    if "timestamp" in fields:
        warn("`timestamp` is OKF v0.1; v0.2 uses `generated.at`")
    gen = fields.get("generated")
    if gen is not None:
        if not isinstance(gen, dict) or not gen.get("by"):
            warn("`generated` needs a `by`")
        elif gen.get("at") is not None and not _aware(gen["at"]):
            warn("`generated.at` needs an ISO 8601 datetime with a UTC offset")
    for e in V.as_list(fields.get("verified")):
        if not isinstance(e, dict) or not e.get("by"):
            warn("each `verified` event needs a `by`")
        elif e.get("at") is not None and not _aware(e["at"]):
            warn("`verified[].at` needs an ISO 8601 datetime with a UTC offset")
    if "stale_after" in fields and not _aware(fields["stale_after"]):
        warn("`stale_after` needs an ISO 8601 datetime with a UTC offset")
    for s in V.as_list(fields.get("sources")):
        if not isinstance(s, dict) or not s.get("resource"):
            warn("each `sources` entry needs a `resource`")


def check_index(v, path, problems):
    fm, body = V.split(path.read_text(encoding="utf-8"))
    if fm is not None:
        try:
            keys = set((V.YAML_RT.load(fm) or {}).keys())
        except Exception:
            keys = {"?"}
        if path.parent.resolve() != v.bundle.resolve() or keys - {"okf_version"}:
            problems.append(("error", path, "index.md takes no frontmatter, except "
                                            "`okf_version` at the bundle root"))


def check_log(v, path, problems):
    lines = [ln for ln in path.read_text(encoding="utf-8").split("\n") if ln.strip()]
    if not lines or not lines[0].startswith("# "):
        problems.append(("error", path, "log.md starts with a top-level `# ` heading"))
    dates = []
    for ln in lines[1:]:
        if ln.startswith("#"):
            m = DATE_HEADING.match(ln)
            if not m:
                problems.append(("error", path, f"log headings are `## YYYY-MM-DD`: {ln!r}"))
            else:
                dates.append(m[1])
        elif not re.match(r"^\s*[-*] ", ln) and not ln.startswith("  "):
            problems.append(("warning", path, f"log entries are bullets: {ln[:60]!r}"))
    if dates != sorted(dates, reverse=True):
        problems.append(("error", path, "log dates must run newest first"))


def prerequisites(notes):
    """{concept id: (note, [(as written, concept id or None)])} for every note
    with `requires`. A target resolves by bundle path (`reading/x`), else by
    filename, the way Obsidian resolves a wikilink."""
    ids = {n.id: n.id for n in notes}
    stems = {}
    for n in notes:
        stems.setdefault(n.path.stem, n.id)
    out = {}
    for n in notes:
        edges = []
        for raw in V.as_list(n.fields.get("requires")):
            if isinstance(raw, list):  # an unquoted [[x]] is YAML for a nested list
                edges.append((str(raw), None))
                continue
            name = str(raw).strip().strip("[]").split("|")[0].strip()
            edges.append((str(raw), ids.get(name) or stems.get(name.split("/")[-1])))
        if edges:
            out[n.id] = (n, edges)
    return out


def find_cycle(graph):
    """One cycle as a list of ids (first == last), or None. `graph` is
    {id: [ids]}; iterative so a long chain can't hit the recursion limit."""
    state = {}  # id -> 1 while on the current path, 2 once finished
    for start in graph:
        if start in state:
            continue
        path, todo = [start], [iter(graph.get(start, ()))]
        state[start] = 1
        while todo:
            for nxt in todo[-1]:
                if state.get(nxt) == 1:
                    return path[path.index(nxt):] + [nxt]
                if nxt not in state:
                    state[nxt] = 1
                    path.append(nxt)
                    todo.append(iter(graph.get(nxt, ())))
                    break
            else:
                state[path.pop()] = 2
                todo.pop()
    return None


def check_graph(v, problems):
    """`requires` edges must point at notes that exist and never loop back;
    `key` is a plain true/false."""
    notes = V.concepts(v)
    graph = {}
    for nid, (n, edges) in prerequisites(notes).items():
        for raw, target in edges:
            if target is None:
                problems.append(("error", n.path, f"`requires` points at {raw!r}, "
                                 "which is no note in the bundle (quote wikilinks: "
                                 '"[[reading/slug]]")'))
        graph[nid] = [t for _, t in edges if t]
    if cycle := find_cycle(graph):
        by_id = {n.id: n for n in notes}
        problems.append(("error", by_id[cycle[0]].path,
                         "`requires` loops: " + " -> ".join(cycle)))
    for n in notes:
        k = n.fields.get("key")
        if k not in (None, "", True, False):
            problems.append(("warning", n.path, f"`key: {k}` should be true or false"))


def check(v):
    problems = []
    for f in sorted(v.bundle.rglob("*.md")):
        if v.excluded(f):
            continue
        if f.name == "index.md":
            check_index(v, f, problems)
        elif f.name == "log.md":
            check_log(v, f, problems)
        else:
            check_concept(v, f, problems)
    check_graph(v, problems)
    return problems
